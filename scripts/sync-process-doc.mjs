#!/usr/bin/env node
/**
 * Regenerates supabase/functions/_shared/pointAt/processDoc.ts from
 * documentation/DOC_POINT_AT_PROCESS.md, the source of truth for Point At's process.
 * An Edge Function cannot read repo files at runtime, so read_process and /api/process
 * serve this generated copy; without regeneration they go stale.
 *
 * Usage: node scripts/sync-process-doc.mjs          (write)
 *        node scripts/sync-process-doc.mjs --check  (exit 1 when the copy is stale)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const SOURCE = "documentation/DOC_POINT_AT_PROCESS.md";
const TARGET = "supabase/functions/_shared/pointAt/processDoc.ts";

/** Escape text so a template literal holds it verbatim. */
export function toTemplateLiteral(text) {
  return text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
}

/** The full generated module for a given process text. */
export function renderProcessModule(text) {
  return `// GENERATED by scripts/sync-process-doc.mjs from ${SOURCE}. Do not edit by hand.
// An Edge Function cannot read repo files at runtime, so the process text is embedded here.
// Run \`node scripts/sync-process-doc.mjs\` whenever that document changes.
export const PROCESS_DOC = \`${toTemplateLiteral(text)}\`;
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const expected = renderProcessModule(readFileSync(root + SOURCE, "utf8"));
  let current = "";
  try {
    current = readFileSync(root + TARGET, "utf8");
  } catch {
    current = "";
  }
  if (process.argv.includes("--check")) {
    if (current !== expected) {
      console.error(`${TARGET} is stale. Run: node scripts/sync-process-doc.mjs`);
      process.exit(1);
    }
    console.log(`${TARGET} is up to date.`);
  } else if (current !== expected) {
    writeFileSync(root + TARGET, expected);
    console.log(`Wrote ${TARGET}.`);
  } else {
    console.log(`${TARGET} already up to date.`);
  }
}
